def lev_dist_w(s1 : str, s2 : str) -> int:
  ans = 0
  dist = list()
  for i in range(0, len(s1) + 1):
    dist.append(list())
    for j in range(0, len(s2) + 1):
      dist[i].append(0)

  for i in range(0, len(s1) + 1):
    dist[i][0] = i
  for i in range(0, len(s2) + 1):
    dist[0][i] = i

  for i in range(1, len(s1) + 1):
    for j in range(1, len(s2) + 1):
      if index_letter_mapping.find(s2[j - 1].lower()) == -1 or index_letter_mapping.find(s1[i - 1].lower()) == -1:
        dist[i][j] = min(dist[i - 1][j] + 1, dist[i][j - 1] + 1, dist[i - 1][j - 1] + maximum_weight_coefficient * (s1[i - 1] != s2[j - 1]))
      else:
        dist[i][j] = min(dist[i - 1][j] + 1, dist[i][j - 1] + 1, dist[i - 1][j - 1] + confusion_matrix[s1[i - 1].lower()][index_letter_mapping.find(s2[j - 1].lower())] * (s1[i - 1] != s2[j - 1]))

  return dist[len(s1)][len(s2)]

